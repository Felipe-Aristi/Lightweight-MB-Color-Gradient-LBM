#!/usr/bin/env bash

set -e

# =======================================================
# Executable name
# =======================================================

EXE=lbm_solver

# =======================================================
# GPU architecture
# =======================================================
# RTX 3050 laptop: SM=86
# RTX 4090:        SM=89

SM=86

# =======================================================
# Source files
# =======================================================

SRC="main.cu kernels.cu"

# =======================================================
# Compile
# =======================================================

echo "Compiling..."

nvcc $SRC \
    -o $EXE \
    -O3 \
    -std=c++20 \
    --extended-lambda \
    -gencode arch=compute_${SM},code=sm_${SM} \
    -gencode arch=compute_${SM},code=compute_${SM} \
    -lineinfo

echo "Compilation finished."

# =======================================================
# Run
# =======================================================

echo "Running ./$EXE ..."
./$EXE